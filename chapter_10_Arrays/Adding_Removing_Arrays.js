let arr = [1, 2, 3]
console.log(arr);

// Add to END - PUSH function
arr.push(4); // adding at the end
console.log(arr);

// Remove from END - POP function
arr.pop();
console.log(arr);

arr.push(4, 6);
console.log(arr);

// Add to BEGAINING
arr.unshift(0);
console.log(arr);

// Remove from BEGAINING
arr.shift();
console.log(arr);