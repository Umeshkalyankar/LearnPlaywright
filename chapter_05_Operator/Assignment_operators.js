// Assignment operators(=) -> Used to store values in variables

// | Operator | Meaning             |
// | -------- | ------------------- |
// | `=`      | Assign              |
// | `+=`     | Add and assign      |
// | `-=`     | Subtract and assign |
// | `*=`     | Multiply and assign |

let a = 10, a = 20;  // assignment can be done in single line
a = 30;
console.log(a);

// +=   Add and assign
let marks = 50;
marks += 10; // marks = marks + 10;
console.log(marks);

// -=    | Subtract and assign
let score = 90;
score -= 10; // score = score - 10;
console.log(score);

// *=    | Multiply and assign
let x = 10;
x *= 5; x = x * 5;
console.log(x);


