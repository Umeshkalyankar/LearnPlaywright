// Arithmetic operators - used to perform calculations (+, -, *, /, %)

let a = 10;
let b = 20;
console.log(a + b); // + is an operator which adds 2 values 
console.log(a - b); // - is an operator which substracts 2 values 
console.log(a * b); // * is an operator which multiple 2 values 
console.log(a / b); // / is an operator which divides 2 values 
console.log(a % b); // % modulus - is an operator which divides - it will give reminder

console.log(37 % 3);

// modulus operator - it will return reminder
// n%2 == even number - it will return 0
// n%2 == odd number - it will return 1