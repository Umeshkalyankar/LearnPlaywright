// Operators are symbols that perform actions on values or variables.

// 1. Arithmetic operators (+, -, *, /, %) -> Used for math calculations.

let a = 10;
let b = 20;
console.log(a + b); // + is an operator which adds 2 values 
console.log(a - b); // - is an operator which substracts 2 values 
console.log(a * b); // * is an operator which multiple 2 values 
console.log(a / b); // / is an operator which divides 2 values 
console.log(a % b); // % modulus - is an operator which divides 2 values i.e a & b

// 2. Assignment operators (=) -> Used to store values in variables.

let age = 28; // = stores value into variable

// 3. Compound operators (+=, -=, /=x, *=; %=)
let marks = 50;
marks += 10; // marks = marks + 10
console.log(marks);

let score = 60;
score -= 5; // score = score - 5;
console.log(score);

// 4. Exponential operators
console.log(2 ** 3); // 2^3 = 8 

