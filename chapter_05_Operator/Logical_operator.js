// Logical operator - Used with conditions
// && - AND Gate - both should be true - then output true
// || - OR Gate - one of should be true - then output true

let a = true;
let b = false;
console.log(a && b); // AND 
console.log(a || b); // OR
console.log(!a);

console.log(5 != "g"); // value 5, g ! - true